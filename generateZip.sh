#!/bin/bash
set -euo pipefail

# Color Variables
GREEN='\033[0;32m'
RED='\033[0;31m'
WHITE='\033[1;37m'
NC='\033[0m'

# Always operate on the repository root, regardless of where this is invoked from
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$REPO_ROOT"

APP_DIR="codebase/rdicidr-0.1.0"
FILE_NAME="assessment-cc-agentic-devops-aws-terraform-sr-01.zip"
ZIP_FILE_FULL_PATH="$REPO_ROOT/$FILE_NAME"

# Remove generated folders
echo -e "${WHITE}Removing unnecessary autogenerated folders and files...${NC}"

# Javascript libraries and frameworks
rm -rf "$APP_DIR/node_modules" \
       "$APP_DIR/dist" \
       "$APP_DIR/build" \
       "$APP_DIR/out" \
       "$APP_DIR/tmp"

echo -e "${GREEN}Unnecessary autogenerated folders and files removed successfully${NC}"

echo -e "${WHITE}Compressing challenge into $FILE_NAME...${NC}"

# Build the archive outside the tree so it can never capture itself, then move it in.
#
# NOTE: .git/, codebase/rdicidr-0.1.0/.github/, .chat-history/ and the terraform
# configuration are all graded artifacts and MUST be included.
#
# Do NOT add a '*.git*' exclude here. It looks like it only drops .git/, but the
# glob also matches .github/ -- which is where the CI pipeline that Part 1 is
# graded on lives -- and .gitignore. It silently removes the work being assessed.
#
# Only .terraform/providers/ is excluded -- plugin binaries, hundreds of MB,
# reproducible from the .terraform.lock.hcl that `terraform init` writes (this
# repo does not ship one, unlike some of the other challenges). The rest of
# .terraform/ stays: modules.json reflects how a candidate structured modules,
# and .terraform/terraform.tfstate is the backend config pointer, which is the
# only record that a candidate chose a remote backend.
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

rm -f "$ZIP_FILE_FULL_PATH"
zip -rq "$TMP_DIR/$FILE_NAME" . \
  -x '*/node_modules/*' \
  -x 'node_modules/*' \
  -x '*/.terraform/providers/*' \
  -x '.terraform/providers/*' \
  -x '*/.DS_Store' \
  -x '.DS_Store'

mv "$TMP_DIR/$FILE_NAME" "$ZIP_FILE_FULL_PATH"

echo -e "${GREEN}Compression complete: $ZIP_FILE_FULL_PATH${NC}"

# ---------------------------------------------------------------------------
# Self-check: the submission is graded from these paths. Fail loudly if any of
# them did not make it into the archive.
# ---------------------------------------------------------------------------
echo -e "\n${WHITE}Verifying submission contents...${NC}"

# Write the listing to a file rather than piping a variable into grep. `grep -q`
# exits on its first match, which closes the pipe while the writer is still
# going; under `set -o pipefail` that EPIPE (exit 141) becomes the status of the
# whole pipeline and turns a successful match into a spurious failure.
LISTING_FILE="$TMP_DIR/listing.txt"
unzip -l "$ZIP_FILE_FULL_PATH" > "$LISTING_FILE"
FAILED=0

check() {
  local label="$1" prefix="$2"
  # `unzip -l` lists a directory as its own zero-length entry, so matching the
  # path alone reports PASS for a folder with nothing in it -- which defeats the
  # only thing this check exists to catch. Require a non-zero-length member
  # *inside* the directory, and don't let a .gitkeep placeholder count as
  # content: a candidate who never wrote a chat log still has one.
  if awk -v p="$prefix" '
        $1 + 0 > 0 && $4 ~ ("^" p) && $4 !~ /\/\.gitkeep$/ { found = 1 }
        END { exit !found }
      ' "$LISTING_FILE"; then
    echo -e "  ${GREEN}PASS${NC}  $label"
  else
    echo -e "  ${RED}FAIL${NC}  $label  (missing from archive, or contains no files)"
    FAILED=1
  fi
}

# NOTE: these are path prefixes anchored to the start of the archive member,
# not whole-line regexes. A leading [.] rather than \. because awk -v mangles
# backslash escapes.
check ".git/                (commit history / branching strategy)" '[.]git/'
check ".github/workflows/   (CI pipeline)"                         'codebase/rdicidr-0[.]1[.]0/[.]github/workflows/'
check ".chat-history/       (AI interaction logs)"                 '[.]chat-history/'
check "terraform/           (AWS infrastructure)  "                'codebase/rdicidr-0[.]1[.]0/terraform/'
check "src/                 (application source)"                  'codebase/rdicidr-0[.]1[.]0/src/'
check "Dockerfile           (container build)"                     'codebase/rdicidr-0[.]1[.]0/Dockerfile'
check "package.json         (CI install/lint/test/build)"          'codebase/rdicidr-0[.]1[.]0/package[.]json'

not_present() {
  local label="$1" pattern="$2"
  if grep -q "$pattern" "$LISTING_FILE"; then
    echo -e "  ${RED}FAIL${NC}  $label leaked into the archive"
    FAILED=1
  else
    echo -e "  ${GREEN}PASS${NC}  $label excluded"
  fi
}

not_present "node_modules" 'node_modules'
not_present ".terraform/providers plugin cache" '/\.terraform/providers/'

echo ""
if [ "$FAILED" -ne 0 ]; then
  echo -e "${RED}Submission is INCOMPLETE. Create the missing directories, populate them, and re-run this script.${NC}"
  echo -e "${RED}Note that .chat-history/ does not ship with the challenge -- you are expected to create it.${NC}"
  exit 1
fi

echo -e "${GREEN}Submission looks complete: $FILE_NAME${NC}"

sleep 2

exit 0
